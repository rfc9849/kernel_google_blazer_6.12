"""Namespace C Binder tracepoint linkage without renaming C structure tags."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[2]
source = root / 'drivers/android/binder_trace.h'
names = set(re.findall(r'TRACE_EVENT\(\s*(binder_\w+)\s*,', source.read_text()))
names.update(re.findall(r'DEFINE_EVENT\([^,]+,\s*(binder_\w+)\s*,', source.read_text()))
names.update(re.findall(r'DEFINE_BINDER_\w+_EVENT\(\s*(binder_\w+)\s*\)', source.read_text()))
if len(names) < 30:
    raise SystemExit('Incomplete C Binder tracepoint list')
lines = ['/* SPDX-License-Identifier: GPL-2.0-only */',
         '/* Generated by scripts/google/gen_binder_trace_prefix.py. */',
         '#ifndef _BINDER_TRACE_PREFIX_H', '#define _BINDER_TRACE_PREFIX_H', '']
for name in sorted(names):
    for prefix in ('__tracepoint_', '__traceiter_', '__probestub_',
                   '__SCK__tp_func_', '__SCT__tp_func_'):
        lines.append(f'#define {prefix}{name} __c_binder_{prefix}{name}')
lines.extend(['', '#endif', ''])
target = source.with_name('binder_trace_prefix.h')
target.write_text('\n'.join(lines))
print(f'Generated {target}: {len(names)} events')
