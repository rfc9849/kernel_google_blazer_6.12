# Generate a header which renames all global symbols defined by the given
# objects by adding a prefix to them. Force-including the header (-include)
# into every object of a driver namespaces a private copy of a library that
# is duplicated between drivers, so that both copies can be linked into the
# same image.
#
# Usage: gen-symbol-prefix.sh <prefix> <objects...> > header.h
set -euo pipefail
PREFIX=$1
shift
NM=${NM:-llvm-nm}

echo "/* SPDX-License-Identifier: GPL-2.0 */"
echo "/* Generated by scripts/google/gen-symbol-prefix.sh. Do not edit. */"
"$NM" -g -U -j "$@" 2>/dev/null | sed "s/^$PREFIX//" |
	grep -v -E '^$|:$|^(__tracepoint|__traceiter|__SCK__|__SCT__|__probestub|__bpf_trace|__event|__trace|__initdone__kmod_|__initcall__kmod_)' |
	sort -u | awk -v p="$PREFIX" '{ printf "#define %s %s%s\n", $1, p, $1 }'
